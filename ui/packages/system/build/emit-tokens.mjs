#!/usr/bin/env node
// 读 DTCG 令牌源 → 解析引用 → 产出 tokens.css / tokens.json / src/generated.ts。
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const TOKENS_DIR = join(ROOT, 'tokens')

async function load(name) {
  return JSON.parse(await readFile(join(TOKENS_DIR, name), 'utf8'))
}

// 把 DTCG 组树展开成 [{ name: '--xh-a-b-c', value, type }]
function flatten(obj, path = []) {
  const out = []
  if (obj && typeof obj === 'object' && '$value' in obj) {
    // 段内的小数点（如刻度 0.5）在 CSS 自定义属性名里非法，替换为下划线
    out.push({ name: `--xh-${path.join('-').replace(/\./g, '_')}`, value: obj.$value, type: obj.$type })
    return out
  }
  for (const [key, child] of Object.entries(obj ?? {})) {
    if (child && typeof child === 'object')
      out.push(...flatten(child, [...path, key]))
  }
  return out
}

// {color.brand.500} → var(--xh-color-brand-500)
function toVar(refPath) {
  return `var(--xh-${refPath.trim().replace(/\./g, '-')})`
}
function resolve(value) {
  if (typeof value === 'number')
    return String(value)
  return String(value).replace(/\{([^}]+)\}/g, (_, p) => toVar(p))
}

function declarations(entries, indent = '    ') {
  return entries.map(e => `${indent}${e.name}: ${resolve(e.value)};`).join('\n')
}

async function main() {
  const primitive = flatten(await load('primitive.json'))
  const base = flatten(await load('semantic.base.json'))
  const light = flatten(await load('semantic.light.json'))
  const dark = flatten(await load('semantic.dark.json'))

  // —— tokens.css ——
  const css = `/* AUTO-GENERATED by build/emit-tokens.mjs — do not edit. */
@layer xihan.tokens {
  /* primitive：任何作用域都不变，只写一次 */
  :where(:root) {
${declarations(primitive)}
  }

  /* 非模式语义（密度等轴的基线合并写法） */
  :where(:root), :where([data-density='comfortable']) {
${declarations(base)}
  }

  /* mode 轴 · 浅色基线块 */
  :where(:root) {
    color-scheme: light;
${declarations(light)}
  }

  /* mode 轴 · 浅色显式取值块 */
  :where([data-theme='light']) {
    color-scheme: light;
${declarations(light)}
  }

  /* mode 轴 · 深色取值块（color-scheme 必须在此，嵌套深色区才能拿到深色原生控件） */
  :where([data-theme='dark']) {
    color-scheme: dark;
${declarations(dark)}
  }
}
`

  // —— tokens.json / generated.ts（默认=浅色，含 primitive + base + light）——
  const flatMap = {}
  for (const e of [...primitive, ...base, ...light]) flatMap[e.name] = resolve(e.value)

  const generatedTs = `/* eslint-disable */
// AUTO-GENERATED by build/emit-tokens.mjs — do not edit.
export const tokens = ${JSON.stringify(flatMap, null, 2)} as const

export type TokenName = keyof typeof tokens
`

  await writeFile(join(ROOT, 'tokens.css'), css)
  await writeFile(join(ROOT, 'tokens.json'), `${JSON.stringify(flatMap, null, 2)}\n`)
  await mkdir(join(ROOT, 'src', 'generated'), { recursive: true })
  await writeFile(join(ROOT, 'src', 'generated', 'tokens.ts'), generatedTs)

  console.log(`[emit-tokens] primitive ${primitive.length} · base ${base.length} · light ${light.length} · dark ${dark.length} → tokens.css / tokens.json / src/generated/tokens.ts`)
}

main()
